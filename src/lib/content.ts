export function levelForPoints(points: number): { title: string; level: number; progress: number } {
  const level = Math.max(0, Math.floor(points / 100))
  const title = LEVELS[Math.min(level, LEVELS.length - 1)]
  return { title, level: level + 1, progress: Math.max(0, points % 100) }
}

